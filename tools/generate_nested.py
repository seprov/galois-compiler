"""Generate a standalone CUDA kernel using the Python 3 IrGL compiler.

This adapter only changes the runtime include, removes graph-app boilerplate,
and sets the block size. Loop mapping and barriers come from the IrGL compiler.
The raw output, adapter diff and checksums are retained next to the result.
"""
from __future__ import annotations
import argparse
import difflib
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--compiler', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--block-size', type=int, choices=[32,64,128,256], default=32)
    args = parser.parse_args()
    compiler, source, output = args.compiler.resolve(), args.source.resolve(), args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, str(compiler/'src/ggc'), str(source),
               '--opt','np','--nps','fg','--npf','4','--cuda-worklist','basic','--cuda-graph','basic',
               '--dis-opt','oiter']
    with tempfile.TemporaryDirectory(prefix='irgl-generate-') as temporary:
        raw_path = Path(temporary) / 'kernel.cu'
        completed = subprocess.run(command + ['-o',str(raw_path)], cwd=temporary,
            env=dict(os.environ, PYTHONHASHSEED='0'), capture_output=True, text=True)
        log = completed.stdout + completed.stderr
        output.with_suffix('.log').write_text(log)
        completed.check_returncode()
        raw = raw_path.read_text()
    if 'Applying Nested Parallelism' not in log or 'not applying' in log:
        raise RuntimeError('IrGL did not apply the requested transformation: ' + log)
    for marker in ['NPInspector1', 'BlockScan', '__syncthreads()', '_np.inspect2']:
        if marker not in raw:
            raise RuntimeError('Generated nested scheduling is missing ' + marker)
    replacements = {
        '#include "gg.h"\n#include "ggcuda.h"': '#include "irgl_nested.cuh"',
        'void kernel_sizing(CSRGraph &, dim3 &, dim3 &);': '',
        '#define TB_SIZE 256': f'#define TB_SIZE {args.block_size}',
        'const char *GGC_OPTIONS =': 'static const char *const GGC_OPTIONS =',
    }
    adapted = raw
    for before, after in replacements.items():
        if adapted.count(before) != 1:
            raise RuntimeError('Unexpected IrGL output: ' + before)
        adapted = adapted.replace(before, after)
    adapted = adapted.replace('roundup(', 'irgl_roundup(')
    adapted = '// Generated by tools/generate_nested.py; do not edit.\n' + adapted + '\n#undef TB_SIZE\n'
    output.write_text(adapted)
    output.with_suffix('.raw.cu').write_text(raw)
    output.with_suffix('.adapter.diff').write_text(''.join(difflib.unified_diff(
        raw.splitlines(True),adapted.splitlines(True),fromfile='raw.cu',tofile=output.name)))
    sha = lambda data: hashlib.sha256(data).hexdigest()
    manifest = {'source_sha256':sha(source.read_bytes()), 'raw_sha256':sha(raw.encode()),
        'output_sha256':sha(adapted.encode()), 'adapter_sha256':sha(Path(__file__).read_bytes()),
        'block_size':args.block_size, 'compiler_command':command,
        'python_version':sys.version,
        'compiler_sources':{str(p.relative_to(compiler)):sha(p.read_bytes())
            for p in sorted((compiler/'src').rglob('*')) if p.is_file() and (p.suffix == '.py' or p.name == 'ggc')}}
    output.with_suffix('.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(output)


if __name__ == '__main__':
    main()
